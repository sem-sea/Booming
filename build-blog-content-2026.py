# ---------- WXR injection ----------
def build_item(slug_key, post_id, post_date, p):
    pub = post_date.strftime("%a, %d %b %Y %H:%M:%S +0000")
    sql = post_date.strftime("%Y-%m-%d %H:%M:%S")
    link_url = f"https://boomingventure.com/blog/{slug_key}/"
    return f"""	<item>
		<title>{p['title']}</title>
		<link>{link_url}</link>
		<pubDate>{pub}</pubDate>
		<dc:creator><![CDATA[ben]]></dc:creator>
		<guid isPermaLink="false">{link_url}</guid>
		<description></description>
		<wp:post_id>{post_id}</wp:post_id>
		<wp:post_date><![CDATA[{sql}]]></wp:post_date>
		<wp:post_name><![CDATA[{slug_key}]]></wp:post_name>
		<wp:status><![CDATA[publish]]></wp:status>
		<wp:post_type><![CDATA[post]]></wp:post_type>
		<category domain="category" nicename="{p['category_slug']}"><![CDATA[{p['category_name']}]]></category>
		<excerpt:encoded><![CDATA[{p['excerpt']}]]></excerpt:encoded>
		<content:encoded><![CDATA[{p['body']}]]></content:encoded>
	</item>
"""

def main():
    if not POSTS:
        sys.exit("No posts defined. Append posts via additional builder fragments.")
    xml = WXR.read_text(encoding="utf-8")

    existing_slugs = set(re.findall(r'<wp:post_name><!\[CDATA\[([^\]]+)\]\]></wp:post_name>', xml))
    new_items = []
    pid = START_ID
    d = START_DATE
    for slug_key, p in POSTS.items():
        if slug_key in existing_slugs:
            print(f"skip (already in WXR): {slug_key}")
            continue
        new_items.append(build_item(slug_key, pid, d, p))
        pid += 1
        d -= timedelta(hours=18)  # spread back in time, newest first

    if not new_items:
        print("Nothing to append (all slugs already exist).")
        return

    block = "".join(new_items)
    # Inject before </channel>
    new_xml, n = re.subn(r'(\s*</channel>)', block + r"\1", xml, count=1)
    if n == 0:
        sys.exit("Could not locate </channel> in WXR.")
    WXR.write_text(new_xml, encoding="utf-8")
    print(f"Appended {len(new_items)} new blog posts to {WXR.name}.")

if __name__ == "__main__":
    main()
