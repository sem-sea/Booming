# ---------- block markup helpers ----------
def tldr(t): return ('<!-- wp:group {"backgroundColor":"booming-50","style":{"border":{"radius":"0.75rem"},"spacing":{"padding":{"top":"1.25rem","right":"1.25rem","bottom":"1.25rem","left":"1.25rem"}}},"layout":{"type":"constrained"}} -->'
                     '<div class="wp-block-group has-booming-50-background-color has-background" style="border-radius:0.75rem;padding:1.25rem">'
                     '<!-- wp:paragraph {"fontSize":"sm","style":{"typography":{"fontWeight":"600","textTransform":"uppercase","letterSpacing":"0.08em"}}} -->'
                     '<p class="has-sm-font-size" style="font-weight:600;text-transform:uppercase;letter-spacing:0.08em">Key takeaways</p>'
                     '<!-- /wp:paragraph -->'
                     '<!-- wp:paragraph --><p>' + t + '</p><!-- /wp:paragraph -->'
                     '</div><!-- /wp:group -->')

def h2(t):  return f'<!-- wp:heading --><h2 class="wp-block-heading">{t}</h2><!-- /wp:heading -->'
def h3(t):  return f'<!-- wp:heading {{"level":3}} --><h3 class="wp-block-heading">{t}</h3><!-- /wp:heading -->'
def p(t):   return f'<!-- wp:paragraph --><p>{t}</p><!-- /wp:paragraph -->'
def cap(t): return f'<!-- wp:paragraph {{"className":"bv-capsule","style":{{"typography":{{"fontWeight":"500"}}}},"fontSize":"lg"}} --><p class="bv-capsule has-lg-font-size" style="font-weight:500">{t}</p><!-- /wp:paragraph -->'
def ul(items):
    li = "\n".join(f"<li>{i}</li>" for i in items)
    return f'<!-- wp:list --><ul class="wp-block-list">\n{li}\n</ul><!-- /wp:list -->'
def ol(items):
    li = "\n".join(f"<li>{i}</li>" for i in items)
    return f'<!-- wp:list {{"ordered":true}} --><ol class="wp-block-list">\n{li}\n</ol><!-- /wp:list -->'
def faq(items):
    out = [h2("Frequently asked questions")]
    for q, a in items:
        out.append(h3(q))
        out.append(p(a))
    return "\n".join(out)
def link(text, url): return f'<a href="{url}" rel="noopener" target="_blank">{text}</a>'
def cta(label, url): return p(f'Want it done with you? <a href="{url}">{label}</a>.')

